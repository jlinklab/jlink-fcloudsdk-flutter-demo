String? kErrorMsg(dynamic code) {
  if (code is BusinessError) {
    return code.errorMessage;
  } else if (code is XCloudAPIException) {
    String pCode = code.code.toString();
    if (errorCodeMapNet[pCode] != null) {
      return errorCodeMapNet[pCode];
    }
    if (errorCodeMapAccount[pCode] != null) {
      return errorCodeMapAccount[pCode];
    }
    if (errorCodeMapDevice[pCode] != null) {
      return errorCodeMapDevice[pCode];
    }
    if (errorCodeMapGeneral[pCode] != null) {
      return errorCodeMapGeneral[pCode];
    }
    if (errorCodeMapAlarm[pCode] != null) {
      return errorCodeMapAlarm[pCode];
    }
    if (errorCodeMapUrlPlay[pCode] != null) {
      return errorCodeMapUrlPlay[pCode];
    }
    if (errorCodeMapMediaTraffic[pCode] != null) {
      return errorCodeMapMediaTraffic[pCode];
    }
    return '错误码:$pCode';
  } else if (code.runtimeType == String) {
    return code;
  }
  return '未知错误:${code.toString()}';
}

